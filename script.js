  const parseDateKey = key => { const [y,m,d] = key.split("-").map(Number); return new Date(y,m-1,d); };
  function zonedDateTimeToIso(key, hour, minute) {
    const [y,m,d] = key.split("-").map(Number);
    const target = Date.UTC(y,m-1,d,hour,minute);
    let guess = target;
    const formatter = new Intl.DateTimeFormat("en-GB", {timeZone,year:"numeric",month:"2-digit",day:"2-digit",hour:"2-digit",minute:"2-digit",hourCycle:"h23"});
    for (let i=0;i<3;i++) {
      const parts = Object.fromEntries(formatter.formatToParts(new Date(guess)).map(p=>[p.type,p.value]));
      const represented = Date.UTC(Number(parts.year),Number(parts.month)-1,Number(parts.day),Number(parts.hour),Number(parts.minute));
      guess += target - represented;
    }
    return new Date(guess);
  }
  function localDateAtMidnightIso(date) {
    return zonedDateTimeToIso(dateKey(date),0,0).toISOString();
  }
  function eventInterval(event) {
    if (event.allDay) return {allDay:true,startKey:event.start.slice(0,10),endKey:event.end.slice(0,10)};
    return {start:Date.parse(event.start),end:Date.parse(event.end),allDay:false};
  }
  function overlaps(start,end,busy) {
    return busy.some(event => {
      const item = eventInterval(event);
      if (item.allDay) return selectedDate >= item.startKey && selectedDate < item.endKey;
      return start < item.end && end > item.start;
    });
  }
  function timesForDay(key) {
    const day = parseDateKey(key);
    if (day.getDay() === 0 || day.getDay() === 6) return [];
    const slots = [];
    let candidate = zonedDateTimeToIso(key,16,0).getTime();
    const closing = zonedDateTimeToIso(key,19,20).getTime();
    let guard = 0;
    while (candidate + 60*60*1000 <= closing && guard++ < 12) {
      const end = candidate + 60*60*1000;
      const conflict = monthBusy.map(eventInterval).filter(item => {
        if (item.allDay) return key >= item.startKey && key < item.endKey;
        return candidate < item.end && end > item.start;
      }).sort((a,b)=>(a.end||Infinity)-(b.end||Infinity))[0];
      if (conflict) {
        if (conflict.allDay) break;
        candidate = conflict.end + 10*60*1000;
      } else {
        slots.push(new Date(candidate));
        candidate += 60*60*1000;
      }
    }
    return slots;
  }
  function renderWeekdays() {
    weekdaysRoot.innerHTML = weekdayNames[currentLang()].map(day=>'<span>'+day+'</span>').join("");
  }
  function renderTimes() {
    timesRoot.innerHTML = "";
    if (availabilityFailed) {
      timesRoot.innerHTML = '<p class="calendar-hint">'+copy("calendarError")+'</p>';
      return;
    }
    if (!selectedDate) {
      timesRoot.innerHTML = '<p class="calendar-hint">'+copy("calendarChooseDay")+'</p>';
      return;
    }
    const day = parseDateKey(selectedDate);
    if (day.getDay() === 0 || day.getDay() === 6) {
      timesRoot.innerHTML = '<p class="calendar-hint">'+copy("calendarClosed")+'</p>';
      return;
    }
    const slots = timesForDay(selectedDate);
    const heading = document.createElement("strong");
    heading.className = "calendar-times-title";
    heading.textContent = copy("calendarSelectTime");
    timesRoot.appendChild(heading);
    const list = document.createElement("div");
    list.className = "calendar-time-list";
    const booked = monthBusy.map(event => ({event,item:eventInterval(event)})).filter(({item}) => item.allDay ? selectedDate>=item.startKey && selectedDate<item.endKey : new Date(item.start).toLocaleDateString("en-CA",{timeZone})===selectedDate);
    const entries = [
      ...booked.filter(({item})=>!item.allDay).map(({item})=>({time:item.start, unavailable:true})),
      ...slots.map(slot=>({time:slot.getTime(), unavailable:false}))
    ].sort((a,b)=>a.time-b.time);
    entries.forEach(entry => {
      const button = document.createElement("button");
      button.type = "button";
      button.className = "calendar-time" + (entry.unavailable ? " unavailable" : "");
      const slotDate = new Date(entry.time);
      const timeLabel = new Intl.DateTimeFormat(currentLang()==="es"?"es-ES":"ca-ES",{timeZone,hour:"2-digit",minute:"2-digit",hourCycle:"h23"}).format(slotDate);
      if (entry.unavailable) {
        button.disabled = true;
        button.textContent = timeLabel + " · No disponible";
      } else {
        button.textContent = timeLabel;
        button.addEventListener("click",()=>{
          list.querySelectorAll("button").forEach(item=>item.classList.remove("selected"));
          button.classList.add("selected");
          chosenSlotIso = slotDate.toISOString();
          bookingSubmit.disabled = false;
          statusRoot.textContent = copy("calendarSelected")+": "+button.textContent;
        });
      }
      list.appendChild(button);
    });
    if (!slots.length && !booked.length) {
      timesRoot.innerHTML += '<p class="calendar-hint">'+copy("calendarNoTimes")+'</p>';
    }
    timesRoot.appendChild(list);
  }
  function renderDays() {
    const year = shownMonth.getFullYear(), month = shownMonth.getMonth();
    monthLabel.textContent = monthNames[currentLang()][month]+" "+year;
    daysRoot.innerHTML = "";
    const first = new Date(year,month,1);
    const offset = (first.getDay()+6)%7;
    const count = new Date(year,month+1,0).getDate();
    for (let i=0;i<offset;i++) {
      const blank = document.createElement("span"); blank.className="calendar-day blank"; daysRoot.appendChild(blank);
    }
    for (let d=1;d<=count;d++) {
      const date = new Date(year,month,d), key = dateKey(date), weekday = date.getDay();
      const button = document.createElement("button");
      button.type="button"; button.className="calendar-day"; button.textContent=String(d);
      const isPast = key < dateKey(today);
      const isWeekend = weekday===0 || weekday===6;
      const isFutureLimit = date > new Date(today.getFullYear()+1,today.getMonth(),today.getDate());
      const noSlots = !isPast && !isWeekend && !isFutureLimit && timesForDay(key).length === 0;
      const unavailable = availabilityFailed || isPast || isWeekend || isFutureLimit || noSlots;
      if (unavailable) button.classList.add("unavailable");
      else button.classList.add("available");
      if (key===selectedDate) button.classList.add("selected");
      button.disabled = unavailable || loading;
      button.setAttribute("aria-label",key+(unavailable?" — "+copy("calendarLegendUnavailable"):" — "+copy("calendarLegendAvailable")));
      button.addEventListener("click",()=>{
        selectedDate=key;
        chosenSlotIso=null; bookingSubmit.disabled=true;
        statusRoot.textContent="";
        renderDays(); renderTimes();
      });
      daysRoot.appendChild(button);
    }
    prevButton.disabled = shownMonth.getFullYear()===today.getFullYear() && shownMonth.getMonth()===today.getMonth();
    nextButton.disabled = shownMonth > new Date(today.getFullYear()+1,today.getMonth(),1);
  }
  async function loadMonth() {
    loading=true; availabilityFailed=false; statusRoot.textContent=copy("calendarLoading");
    renderDays(); renderTimes();
    const first = new Date(shownMonth.getFullYear(),shownMonth.getMonth(),1);
    const last = new Date(shownMonth.getFullYear(),shownMonth.getMonth()+1,1);
    const middle = new Date(first.getFullYear(),first.getMonth(),16);
    const chunks = [[first,middle],[middle,last]].filter(([a,b])=>b>a);
    try {
      const responses = await Promise.all(chunks.map(([a,b])=>{
        const url="/api/google/availability?start="+encodeURIComponent(localDateAtMidnightIso(a))+"&end="+encodeURIComponent(localDateAtMidnightIso(b));
        return fetch(url,{cache:"no-store"}).then(r=>r.json().then(data=>{if(!r.ok||!data.ok) throw new Error(data.message||"Availability error");return data;}));
      }));
      monthBusy = responses.flatMap(data=>data.busy||[]);
      loading=false; availabilityFailed=false; statusRoot.textContent="";
      renderDays();
      if (selectedDate && selectedDate.slice(0,7)===yearMonthKey()) renderTimes();
      else { selectedDate=null; renderTimes(); }
    } catch(error) {
      loading=false; monthBusy=[]; availabilityFailed=true;
      renderDays(); renderTimes();
      statusRoot.textContent=copy("calendarError");
    }
  }
  function yearMonthKey(){return shownMonth.getFullYear()+"-"+pad(shownMonth.getMonth()+1);}
  prevButton.addEventListener("click",()=>{if(!prevButton.disabled){shownMonth=new Date(shownMonth.getFullYear(),shownMonth.getMonth()-1,1);selectedDate=null;chosenSlotIso=null;bookingSubmit.disabled=true;loadMonth();}});
  nextButton.addEventListener("click",()=>{if(!nextButton.disabled){shownMonth=new Date(shownMonth.getFullYear(),shownMonth.getMonth()+1,1);selectedDate=null;chosenSlotIso=null;bookingSubmit.disabled=true;loadMonth();}});
  renderWeekdays();
  loadMonth();
  document.addEventListener("booking:confirmed",()=>{chosenSlotIso=null;selectedDate=null;bookingSubmit.disabled=true;bookingSubmit.textContent=copy("bookingConfirm");loadMonth();});
  document.querySelectorAll("[data-lang]").forEach(button=>button.addEventListener("click",()=>{
    renderWeekdays(); renderDays(); renderTimes();
    prevButton.setAttribute("aria-label",copy("calendarPrev"));
    nextButton.setAttribute("aria-label",copy("calendarNext"));
  }));
